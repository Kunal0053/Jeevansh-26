
import axios from 'axios';

const BASE_URL =
  import.meta.env.VITE_API_URL ||
  'https://jeevansh-backend.onrender.com';

const API_URL = BASE_URL.replace(/\/+$/, '').endsWith('/api')
  ? BASE_URL.replace(/\/+$/, '')
  : `${BASE_URL.replace(/\/+$/, '')}/api`;

// Check nearby blood banks.
// NOTE: This function currently uses mock data.
export async function checkBanks(bloodType) {
  const mockBanks = [
    {
      id: 'bank-1',
      name: 'City Hospital Blood Bank',
      distance: 3.2,
      stock: { 'B+': 4, 'O+': 2 },
    },
    {
      id: 'bank-2',
      name: 'Red Cross Society',
      distance: 7.8,
      stock: { 'B+': 0, 'O-': 1 },
    },
    {
      id: 'bank-3',
      name: 'Govt Medical College',
      distance: 12.1,
      stock: { 'B+': 2, 'A+': 5 },
    },
  ];

  return mockBanks
    .map((bank) => ({
      ...bank,
      hasStock: (bank.stock[bloodType] || 0) > 0,
      unitsAvailable: bank.stock[bloodType] || 0,
    }))
    .sort((a, b) => a.distance - b.distance);
}

// Get the requester's current GPS coordinates.
function getCurrentLocation() {
  return new Promise((resolve, reject) => {
    if (!navigator.geolocation) {
      reject(
        new Error('Geolocation is not supported by this browser.')
      );
      return;
    }

    navigator.geolocation.getCurrentPosition(
      (position) => resolve(position.coords),
      (error) => {
        const messages = {
          1: 'Location permission denied. Please allow location access.',
          2: 'Your current location could not be determined.',
          3: 'Location request timed out. Please try again.',
        };

        reject(
          new Error(
            messages[error.code] ||
              'Unable to fetch your current location.'
          )
        );
      },
      {
        enableHighAccuracy: true,
        timeout: 15000,
        maximumAge: 0,
      }
    );
  });
}

// Create a blood request using the stable ID generated by RequestForm.
// Reuse this ID for retries of the same form submission.
export async function createRequest(data) {
  if (!data?.clientRequestId) {
    throw new Error(
      'Request ID is missing. Please return to the request form and submit again.'
    );
  }

  const clientRequestId = data.clientRequestId;
  const position = await getCurrentLocation();

  const payload = {
    client_request_id: clientRequestId,
    blood_type: data.bloodType,
    latitude: position.latitude,
    longitude: position.longitude,
    patient_age: parseInt(data.patientAge, 10) || null,
    patient_gender: data.patientGender || null,
    units: parseInt(data.units, 10) || 1,
    hospital_name: data.hospital || null,
    location_text: data.location || null,
  };

  const response = await axios.post(
    `${API_URL}/requests`,
    payload
  );

  const result = response.data;

  if (!result?.id) {
    throw new Error(
      'The server response did not contain a request ID.'
    );
  }

  return {
    ...result,
    clientRequestId,
    shortId: result.id.slice(-6),
    matchedDonors: result.matched_donors || [],
  };
}

// Fetch the latest status for an existing request.
export async function getRequestStatus(requestId) {
  if (!requestId) {
    throw new Error('Request ID is required to fetch status.');
  }

  const response = await axios.get(
    `${API_URL}/requests/${encodeURIComponent(requestId)}/status`
  );

  return response.data;
}

// Fetch donor contact information for the requester.
export async function getDonorInfoForPatient(requestId) {
  if (!requestId) {
    throw new Error('Request ID is required to fetch donor information.');
  }

  const response = await axios.get(
    `${API_URL}/requests/${encodeURIComponent(requestId)}/donor-info`
  );

  return response.data;
}
